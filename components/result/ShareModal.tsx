"use client";

import React, { useState, useEffect } from "react";
import Image from "next/image";
import { Share2, Link as LinkIcon, Download, X, Check } from "lucide-react";
import { useLanguage } from "@/components/LanguageProvider";

interface ShareModalProps {
  isOpen: boolean;
  onClose: () => void;
  publicToken: string;
  archetypeId: string;
}

export const ShareModal: React.FC<ShareModalProps> = ({ isOpen, onClose, publicToken, archetypeId }) => {
  const { language } = useLanguage();
  const [copied, setCopied] = useState(false);
  const [shareUrl, setShareUrl] = useState("");

  useEffect(() => {
    if (typeof window !== "undefined") {
      setShareUrl(`${window.location.origin}/r/${publicToken}`);
    }
  }, [publicToken]);

  const t = {
    en: {
      title: "Share your Archetype",
      shareNative: "Share link",
      copyLink: "Copy link",
      download: "Download image",
      copied: "Link copied"
    },
    tr: {
      title: "Archetype'ını Paylaş",
      shareNative: "Bağlantıyı Paylaş",
      copyLink: "Bağlantıyı Kopyala",
      download: "Görseli İndir",
      copied: "Bağlantı kopyalandı"
    }
  };

  const c = t[language];

  if (!isOpen) return null;

  const handleNativeShare = async () => {
    console.log("[Analytics] share_native_clicked");
    if (navigator.share) {
      try {
        await navigator.share({
          title: "Archetype",
          text: "Discover your Archetype pattern.",
          url: shareUrl,
        });
      } catch (err) {
        console.error("Error sharing:", err);
      }
    } else {
      handleCopyLink();
    }
  };

  const handleCopyLink = async () => {
    console.log("[Analytics] share_link_copied");
    try {
      await navigator.clipboard.writeText(shareUrl);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.error("Error copying:", err);
    }
  };

  const handleDownload = () => {
    console.log("[Analytics] share_image_downloaded");
    const imageUrl = `/api/og?archetype=${archetypeId}`;
    
    // Create a temporary link to force download
    const link = document.createElement("a");
    link.href = imageUrl;
    link.download = `Archetype_${archetypeId.toLowerCase()}.png`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-in fade-in duration-200">
      
      {/* Click outside to close */}
      <div className="absolute inset-0" onClick={onClose} />

      {/* Modal Content */}
      <div className="relative z-10 w-full max-w-md bg-zinc-950 border border-zinc-800 p-6 flex flex-col items-center animate-in zoom-in-95 duration-200 shadow-2xl">
        
        <button 
          onClick={onClose}
          className="absolute top-4 right-4 p-2 text-zinc-500 hover:text-white transition-colors"
        >
          <X size={20} strokeWidth={1} />
        </button>

        <h3 className="text-white font-mono uppercase tracking-[0.2em] text-xs mb-8 mt-2">
          {c.title}
        </h3>

        {/* Share Preview Image (OG Image) */}
        <div className="w-full aspect-[1200/630] bg-zinc-900 border border-zinc-800 mb-8 relative overflow-hidden">
          {/* We show the same image generated by OG route */}
          <Image 
            src={`/api/og?archetype=${archetypeId}`} 
            alt="Share preview" 
            fill 
            className="object-cover opacity-90"
            unoptimized // It's a dynamic API route
          />
        </div>

        {/* Actions */}
        <div className="w-full flex flex-col gap-3">
          {typeof navigator !== "undefined" && typeof navigator.share === "function" && (
            <button 
              onClick={handleNativeShare}
              className="flex items-center justify-center gap-3 w-full border border-zinc-700 bg-zinc-900/50 hover:bg-zinc-800 hover:border-zinc-500 text-zinc-300 hover:text-white transition-all px-4 py-3 font-mono text-[0.65rem] tracking-widest uppercase"
            >
              <Share2 size={14} />
              {c.shareNative}
            </button>
          )}

          <button 
            onClick={handleCopyLink}
            className="flex items-center justify-center gap-3 w-full border border-zinc-800 hover:border-zinc-600 text-zinc-400 hover:text-white transition-colors px-4 py-3 font-mono text-[0.65rem] tracking-widest uppercase"
          >
            {copied ? <Check size={14} className="text-white" /> : <LinkIcon size={14} />}
            {copied ? c.copied : c.copyLink}
          </button>

          <button 
            onClick={handleDownload}
            className="flex items-center justify-center gap-3 w-full border border-zinc-800 hover:border-zinc-600 text-zinc-400 hover:text-white transition-colors px-4 py-3 font-mono text-[0.65rem] tracking-widest uppercase"
          >
            <Download size={14} />
            {c.download}
          </button>
        </div>
      </div>
    </div>
  );
};
